def by_skill(skill: str) -> list[Item]:
    return [i for i in ITEMS if i.skill == skill]


def review_quiz() -> list[Question]:
    """تقييم المراجعة: سؤال اختيار واحد على الأقل من كل مهارة، وصح/خطأ لمهارات بديلة، فيغطي الوحدة كلها."""
    out: list[Question] = []
    for n, skill in enumerate(SKILLS):
        items = by_skill(skill)
        mcq = [i for i in items if i.choices]
        tf = [i for i in items if not i.choices]
        out.append(mcq[0].question(n))
        if n % 2 == 0 and tf:
            out.append(tf[0].question())
    return out
