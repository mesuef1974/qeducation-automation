def questions_for(title: str) -> list[Question]:
    """شريحة الجزء من بنك الموضوع، بتدوير إن زادت الأجزاء على البنك؛ وفارغة إن لا موضوع."""
    pool = BANK.get(topic_of(title), [])
    if not pool:
        return []
    start = ((part_of(title) - 1) * PER_QUIZ) % len(pool)
    return pool[start:start + PER_QUIZ] or pool[:PER_QUIZ]
