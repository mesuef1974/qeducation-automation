import re

from neo.domain.assessment import MCQ, TF, Question

PER_QUIZ = 5


def topic_of(title: str) -> str:
    """«المميزات الاساسية للدالة التربيعية 2» → الموضوع بلا رقم، مع توحيد الهمزة والتاء المربوطة."""
    t = re.sub(r"\s*\d+\s*$", "", title.strip())
    t = re.sub(r"[إأآ]", "ا", t).replace("ة", "ه").replace("ى", "ي")
    return re.sub(r"\s+", " ", t)


def part_of(title: str) -> int:
    m = re.search(r"(\d+)\s*$", title.strip())
    return int(m.group(1)) if m else 1


def _mcq(text, correct, *others):
    return Question(MCQ, text, (correct, *others), 0)


def _tf(text, answer):
    return Question(TF, text, answer=answer)


