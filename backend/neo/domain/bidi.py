"""
اتجاه الأرقام في النص العربي.

في سطر عربي تأخذ الأرقام التالية لحرف عربي اتجاه السطر، فيظهر النطاق «2–4» مقلوبًا «4–2» والعام «2026–2027»
«2027–2026»، ورقم تدريب فيه حرف لاتيني («17a») يجرّ ما بعده من أرقام إلى اتجاهه فيختلط ترتيبها.
علامتا الاتجاه غير المرئيتين تصلحان ذلك في الواجهة، وفي Word وExcel والرسائل حيث يُلصق النص.
"""
import re

LRM, RLM = "\u200e", "\u200f"
_RANGE = re.compile(r"(?<![\d\u200e])(\d+[–-]\d+)")
_LATIN = re.compile(r"[A-Za-z]")


def ltr(text: str) -> str:
    """نطاق أو رقم بإشارة («2–4»، «+25.3») يُعرض من اليسار إلى اليمين داخل سطر عربي."""
    return f"{LRM}{text}"


def fix_ranges(text: str) -> str:
    """كل نطاق رقمي ملتصق («2026-2027»، «144–163») في نص عربي يُعرض بترتيبه. التكرار آمن."""
    return _RANGE.sub(lambda m: LRM + m.group(1), text)


def latin_item(item: str) -> str:
    """رقم فيه حرف لاتيني («17a») لا يقلب ترتيب ما يليه من أرقام في القائمة."""
    return f"{item}{RLM}" if _LATIN.search(item) else item
