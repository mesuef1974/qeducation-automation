def book_for(grade: int, term: int, tracks: str) -> Book | None:
    """الكتاب المطابق؛ المسار المحدد يسبق «» حتى لا يأخذ صف علمي كتاب صف بلا مسار."""
    found = [(track, b) for (g, t, track), b in BOOKS.items() if g == grade and t == term and track in (tracks or "")]
    found.sort(key=lambda x: -len(x[0]))
    return found[0][1] if found else None
